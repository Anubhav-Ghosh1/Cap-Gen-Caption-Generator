/**
 * Caption style presets, shared between the browser live-preview (CSS) and the
 * server-side ASS subtitle generator. Scales are fractions of the video height
 * so styles look consistent at any resolution.
 */

export type CaptionPosition = "bottom" | "center" | "top";
export type CaptionMode = "sentence" | "chunks" | "word" | "karaoke";
export type CaptionAnimation = "none" | "pop" | "fade";

export interface CaptionStyle {
  id: string;
  name: string;
  mode: CaptionMode;
  position: CaptionPosition;
  /** font size as a fraction of video height, e.g. 0.05 */
  fontScale: number;
  /** stroke width as a fraction of video height */
  outlineScale: number;
  textColor: string; // css hex, e.g. "#FFFFFF"
  highlightColor: string; // karaoke fill color
  outlineColor: string;
  /** Font resolved by the system (must exist in fontconfig / macOS fonts) */
  fontFamily: string;
  bold: boolean;
  italic: boolean;
  /** extra tracking, in em units (e.g. 0.01 = slight, 0.1 = wide) */
  letterSpacing: number;
  uppercase: boolean;
  /** solid box behind text (BorderStyle 3 in ASS) */
  box: boolean;
  /** soft blurred halo behind the text (rendered as a blurred outline layer) */
  glow?: boolean;
  wordsPerChunk: number; // used by "chunks" mode
  /** distance from the nearest edge as a fraction of video height */
  marginV: number;
  /** entrance animation for each caption line */
  animation?: CaptionAnimation;
}

