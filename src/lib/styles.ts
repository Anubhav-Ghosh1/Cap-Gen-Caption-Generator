export function getPreset(id: string): CaptionStyle {
  return PRESETS.find((p) => p.id === id) ?? PRESETS[0];
}

/** Clamp a margin value so captions never leave the frame. */
export function clampMarginV(v: number): number {
  return Math.min(0.45, Math.max(0.02, v));
}
